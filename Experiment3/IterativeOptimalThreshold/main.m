%======================================================================
% 主函数 —— 迭代阈值分割（Iterative Optimal Threshold）
%
% 本程序演示如何使用"迭代法"自动找到一个最优的灰度阈值 T，
% 用这个阈值把灰度图分成"前景"和"背景"两部分（二值化）。
%
% 什么是阈值分割？
%   灰度图像中，每个像素的亮度值在 0（黑）~ 255（白）之间。
%   阈值分割就是：选定一个阈值 T，然后把图像中每个像素的灰度值
%   与 T 做比较：
%     - 灰度值 >= T  → 归类为"前景"（通常设为白色 255）
%     - 灰度值 <  T  → 归类为"背景"（通常设为黑色 0）
%   结果得到一张"二值图像"（每个像素只有黑白两种颜色）。
%
%   举例：假设一张证件照，想要把文字和背景分开，
%         设 T=128，则灰度值 >=128 的像素（文字/前景）变成白色，
%         灰度值 <128 的像素（背景）变成黑色。
%
% 迭代法的核心思想：
%   先随便猜一个初始阈值，然后反复改进它。
%   每一次迭代，根据当前阈值把图像分成两组，分别算两组的"平均亮度"，
%   然后用两个平均值的平均值作为新的阈值。
%   重复这个过程，直到阈值几乎不再变化（收敛）。
%   这个过程像极了"猜测 → 反馈 → 调整 → 再猜测"的循环，直到答案稳定。
%======================================================================


% ---------- 第一步：准备工作（清理环境） ----------
% clc;          清空命令行窗口（把命令行里之前的内容都清除）
% clear all;    清除工作区（workspace）中的所有变量
%               —— 防止之前运行的程序留下旧变量，影响本次运行
% close all;    关闭所有打开的图形窗口（figure 窗口）
%               —— 避免之前画图留下的窗口干扰
clc; clear all; close all;


% ---------- 第二步：读取图片 ----------
% imread('testimg.jpg') 读取当前文件夹下的 testimg.jpg 图片
% 读入的 img 是一个矩阵：
%   - 彩色图：rows × cols × 3（三维），第3维是 R/G/B 三个颜色通道
%   - MATLAB 默认读入为 uint8 类型（无符号8位整数，范围 0~255）
img = imread('testimg.jpg');


% ---------- 第三步：彩色图转灰度图 ----------
% rgb2gray() 将彩色图像（RGB）转换为灰度图像
% 为什么需要这一步？
%   - 灰度图只有 1 个通道（亮度），处理更简单
%   - 阈值分割主要关心亮度差异，不需要颜色信息
%   - 转换公式（大致）：灰度 = 0.299×R + 0.587×G + 0.114×B
%     （绿色权重最大，因为人眼对绿色最敏感）
img = rgb2gray(img);


% ---------- 第四步：调用迭代阈值分割函数 ----------
% 调用自定义函数 MyOptimalThreshold，传入灰度图 img
% 该函数会自动找到一个最优阈值 T，并用 T 对图像做二值化分割
% 返回值：
%   OptimalThreshold_result —— 二值化后的图像（黑白图）
%   T                      —— 找到的最优阈值（一个 0~255 之间的数）
%
% 这里同时返回了阈值 T，因为后面要在标题中显示它的值
[OptimalThreshold_result, T] = MyOptimalThreshold(img);


% ---------- 第五步：显示最终结果 ----------
% figure;           创建并激活一个新的图形窗口
%                   如果不加这一行，imshow 会画在上一张图上，覆盖掉之前的
% imshow(...)       在当前 figure 窗口中显示图像
% title(...)        给图像加一个标题
%   ['xxx' num2str(round(T)) 'yyy'] 是字符串拼接语法：
%     - ['字符串1' '字符串2'] 用方括号拼接字符串
%     - num2str(T) 把数字 T 转成字符串
%     - round(T) 对 T 四舍五入取整（阈值通常是整数）
%   最终标题形如："OptimalThreshold Result (T = 128)"
figure;
imshow(OptimalThreshold_result);
title(['OptimalThreshold Result (T = ' num2str(round(T)) ')']);
