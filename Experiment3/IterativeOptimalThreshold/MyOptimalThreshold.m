%======================================================================
% 迭代最优阈值选择函数 —— MyOptimalThreshold
%
% 什么是"迭代最优阈值"？
%   "迭代"就是"不断重复、逐步逼近正确答案"的意思。
%   这个函数不需要你手动指定阈值，而是自动从图像出发，一步步算出最优阈值。
%
% 迭代阈值分割的数学原理（逐步讲解）：
%   假设当前有一个猜测的阈值 T（初始值由图像的 min/max 决定）
%   第 1 步：用 T 把所有像素分成两组
%     G1 = {像素灰度值 >= T}  （较亮的那组）
%     G2 = {像素灰度值 <  T}  （较暗的那组）
%   第 2 步：分别计算 G1 和 G2 的"平均灰度值"（即"组内像素亮度的平均值"）
%     u1 = mean(G1)  （G1 的平均亮度）
%     u2 = mean(G2)  （G2 的平均亮度）
%   第 3 步：用 u1 和 u2 的平均值作为新的阈值 T_new = (u1 + u2) / 2
%   第 4 步：重复第 1~3 步，直到 |T_new - T| < epsilon（阈值不再明显变化）
%
% 为什么这个方法能找到"最优"阈值？
%   直观理解：前景和背景通常有不同的亮度分布。
%   如果阈值 T 选得好，它应该恰好落在两组像素亮度的"分界线"上。
%   当 T 选得好时，G1 的平均值 u1 和 G2 的平均值 u2 差距最大，
%   而 (u1+u2)/2 作为新阈值，会把这个"分界线"推得更准确。
%   迭代几次后，T 就会稳定在一个最佳位置。
%
%======================================================================


function [OptimalThreshold_result, T] = MyOptimalThreshold(img)

    % -----------------------------------------------------------------------
    % 【第 0 步】类型转换 —— 把图像从整数转为浮点数，方便后续数学运算
    % -----------------------------------------------------------------------
    % MATLAB 读取图像默认是 uint8 类型（无符号8位整数，范围 0~255）
    % uint8 做除法时会产生问题（比如 200/3 在 uint8 下等于 66，不是小数）
    % 所以先用 double() 把图像转成双精度浮点数，保留小数精度。
    % 转换后 img_d 的类型从 uint8 变成 double，但数值大小不变（200 还是 200.0）
    img_d = double(img);


    % -----------------------------------------------------------------------
    % 【第 1 步】确定初始阈值 T₀（第一次猜测）
    % -----------------------------------------------------------------------
    % 选取图像灰度范围的"中点"作为初始猜测
    % min(img_d(:)) —— 找到图像中灰度值最小的像素
    %   语法解释：img_d(:) 把 2D 矩阵展开成 1D 列向量，min() 在所有像素中找最小值
    % max(img_d(:)) —— 找到图像中灰度值最大的像素
    % (min + max) / 2 —— 取灰度范围的中间值
    %
    % 为什么这样选？
    %   比如图像灰度范围是 [30, 220]，初始 T = (30+220)/2 = 125
    %   这是一个合理的起点——既不太高也不太低
    T = (min(img_d(:)) + max(img_d(:))) / 2;


    % -----------------------------------------------------------------------
    % 【第 2 步】设置收敛条件
    % -----------------------------------------------------------------------
    % epsilon = 0.5 表示：两次迭代之间阈值的变化小于 0.5，就认为已经收敛
    % 为什么设成 0.5？因为灰度值都是整数（0~255），阈值变化小于 1 像素级别，
    %   再追求更精确已经没有实际意义了
    % 这是迭代算法的"停止条件"——满足这个条件就退出循环
    epsilon = 0.5;


    % -----------------------------------------------------------------------
    % 【第 3 步】记录阈值变化历史（用于画收敛图）
    % -----------------------------------------------------------------------
    % threshold_history 是一个数组，用来记录每次迭代后阈值 T 的值
    % 后面会用 plot() 把这个变化过程画出来，直观看到 T 是如何逐步收敛的
    % 初始值就是上面算出的 T
    threshold_history = T;


    % -----------------------------------------------------------------------
    % 【第 4 步】开始迭代循环
    % -----------------------------------------------------------------------
    % maxIter = 100 是最大迭代次数上限
    %   —— 防止代码陷入死循环（比如图像太特殊，永远收敛不了）
    % for iter = 1:maxIter
    %   —— 从 iter=1 开始，每次加1，一直跑到 maxIter=100
    maxIter = 100;
    for iter = 1:maxIter

        % ----- 4.1 根据当前阈值 T，把像素分成两组 -----
        %
        % img_d(img_d >= T)
        %   语法解释：MATLAB 的"逻辑索引"
        %   img_d >= T 产生一个逻辑数组（true/false），形状和图像一样大
        %   img_d(...) 只保留对应位置为 true 的像素值
        %   结果：G1 是一个列向量，包含所有灰度值 >= T 的像素
        %
        % G1：较亮的那组像素（灰度 >= T）
        % G2：较暗的那组像素（灰度 < T）
        G1 = img_d(img_d >= T);
        G2 = img_d(img_d < T);


        % ----- 4.2 计算两组的平均灰度值 -----
        %
        % mean() 函数计算平均值（所有元素之和 / 元素个数）
        % u1 = G1 的平均值（较亮组的平均亮度）
        % u2 = G2 的平均值（较暗组的平均亮度）
        %
        % 为什么计算平均值？
        %   直观理解：每组像素的"平均亮度"代表了该组的"典型亮度"。
        %   前景和背景的平均亮度差距越大，说明分得越清楚（阈值选得越好）。
        u1 = mean(G1);
        u2 = mean(G2);


        % ----- 4.3 用两组的平均值算出新的阈值 -----
        %
        % T_new = (u1 + u2) / 2
        %   取两组平均亮度的"中点"作为新阈值
        %
        % 为什么这样合理？
        %   如果 u1=200，u2=50，说明 G1（较亮）集中在200附近，G2（较暗）集中在50附近
        %   那么最优阈值应该取在 200 和 50 的中间，即 (200+50)/2 = 125
        %   这个阈值恰好是两组像素的"分界线"。
        T_new = (u1 + u2) / 2;


        % ----- 4.4 记录新阈值（用于绘图） -----
        %
        % threshold_history = [threshold_history, T_new]
        %   把新阈值 T_new 添加到数组末尾
        %   MATLAB 中用方括号 [] 做数组拼接
        %   循环结束后，threshold_history 记录了 T 从初始值到收敛值的完整变化过程
        %
        % %#ok<AGROW> 是 MATLAB 的一个语法警告抑制指令
        %   —— MATLAB 提示数组每次拼接都会重新分配内存，效率略低，
        %     但对只有几十次的循环来说完全可以接受，这里忽略这个警告
        threshold_history = [threshold_history, T_new];


        % ----- 4.5 判断是否收敛（停止条件） -----
        %
        % abs(T_new - T)  计算两次阈值的差的绝对值（不考虑正负方向）
        % 如果差值 < epsilon，说明新阈值和旧阈值非常接近，已经稳定
        %
        % if abs(T_new - T) < epsilon
        %     T = T_new;    —— 更新 T 为新值
        %     break;        —— 立即退出 for 循环（迭代完成）
        % end
        %
        % break 是"跳出循环"的关键字，程序执行到这里就退出 for 循环，
        % 不再执行后面的 T = T_new
        if abs(T_new - T) < epsilon
            T = T_new;
            break;
        end

        % 如果没有触发 break，说明还没收敛，把 T 更新为 T_new，继续下一次迭代
        T = T_new;

    end   % 循环结束


    % -----------------------------------------------------------------------
    % 【第 5 步】用找到的最优阈值做二值化分割
    % -----------------------------------------------------------------------
    %
    % 二值化（Thresholding）：把灰度图变成只有黑白两色的图
    %   - 像素 >= T  →  255（白色，前景）
    %   - 像素 <  T  →  0  （黑色，背景）
    %
    % 为什么是 255 和 0？因为这是 uint8 的范围（0~255）
    % 白色 = 255，黑色 = 0，这是图像处理的惯例。
    %
    % OptimalThreshold_result = img;
    %   —— 先复制一份原图，保留结构
    %   然后用逻辑索引批量修改像素值：
    %   img >= T 生成一个 true/false 数组，对应位置为 true 的像素赋值为 255
    %   img <  T 对应位置为 true 的像素赋值为 0
    %
    % 最后 uint8() 把结果从 double 转回 uint8 格式
    %   uint8 是图像显示的标准格式，imshow() 要求输入是 uint8
    OptimalThreshold_result = img;
    OptimalThreshold_result(img >= T) = 255;
    OptimalThreshold_result(img < T) = 0;
    OptimalThreshold_result = uint8(OptimalThreshold_result);


    % -----------------------------------------------------------------------
    % 【第 6 步】绘制阈值 T 的收敛过程图（便于观察迭代是否正常收敛）
    % -----------------------------------------------------------------------
    %
    % figure;           新建一个图形窗口（显示收敛曲线的图）
    %
    % plot(threshold_history, '-o', 'LineWidth', 1.5);
    %   plot() 是 MATLAB 的绘图函数
    %   threshold_history —— 要画的数据（数组），横轴是迭代次数（1,2,3,...），纵轴是 T 的值
    %   '-o'             —— 线型：实线 + 圆点标记（每个数据点画一个圆圈）
    %   'LineWidth', 1.5 —— 线条粗细设为 1.5 磅，看起来更清晰
    %
    % xlabel('Iteration');    给横轴加标签"迭代次数"
    % ylabel('Threshold T'); 给纵轴加标签"阈值 T"
    %
    % title(['Iterative Optimal Threshold (Final T = ' num2str(round(T)) ')']);
    %   给图加标题，显示最终收敛的阈值 T（round 四舍五入取整）
    %
    % grid on;                打开网格线，方便读数
    %
    % 通常你会看到一条快速下降/上升然后趋于平稳的曲线，
    % 这条曲线平稳的地方就是最优阈值。
    figure;
    plot(threshold_history, '-o', 'LineWidth', 1.5);
    xlabel('Iteration');
    ylabel('Threshold T');
    title(['Iterative Optimal Threshold (Final T = ' num2str(round(T)) ')']);
    grid on;

end   % 函数结束
