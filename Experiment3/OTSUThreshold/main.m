%======================================================================
% 主函数 —— OTSU 自动阈值分割
%
% 本程序演示如何使用 OTSU（大津法）自动找到一个最优阈值，
% 把灰度图像分割成前景和背景两部分。
%
% 什么是 OTSU（大津法）？
%   OTSU 是一种完全"自动"的阈值选择方法，由日本学者大津展之于 1979 年提出。
%   它不需要你手动设置任何参数，算法会自动从图像本身找到最优阈值。
%
% OTSU 的核心思想：
%   OTSU 认为：好的阈值应该让"前景"和"背景"两个类之间的差异最大。
%   这个"差异"用"类间方差"（σ_B²）来量化。
%   遍历所有可能的阈值（0~255），找出使 σ_B² 最大的那个，就是最优阈值。
%
% OTSU 和迭代法的区别：
%   迭代法：不断"迭代"逐步逼近最优阈值（像反复猜测正确答案）
%   OTSU：一次性"穷举"所有可能的阈值，数学上直接选出最优的那个（更精确，但计算量略大）
%   两者都是自动的，不需要手动指定阈值。
%======================================================================


% ---------- 第一步：准备工作（清理环境） ----------
% clc;     清空命令行
% clear all;  清除工作区所有变量
% close all;  关闭所有图形窗口
clc; clear all; close all;


% ---------- 第二步：读取图片 ----------
% imread('mytest.jpg') 读取当前目录下的 mytest.jpg
img = imread('mytest.jpg');


% ---------- 第三步：彩色图转灰度图 ----------
% rgb2gray() 把 RGB 彩色图转成灰度图
% 灰度图只有亮度信息（0=黑，255=白），阈值分割只需要亮度
img = rgb2gray(img);


% ---------- 第四步：调用 OTSU 阈值分割函数 ----------
% 调用自定义函数 MyOTSU，传入灰度图
% OTSU 不需要手动设置任何参数，只需要图像本身
% 返回值：
%   OTSU_result —— 二值化后的图像（黑白图，每个像素非黑即白）
OTSU_result = MyOTSU(img);


% ---------- 第五步：显示结果 ----------
% figure;     新建一个窗口
% imshow(...) 显示二值化后的图像
% title(...)  添加标题
figure;
imshow(OTSU_result);
title('OTSU Result');
