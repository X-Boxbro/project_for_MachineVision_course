%======================================================================
% OTSU 自动阈值分割函数 —— MyOTSU
%
% OTSU 算法的数学原理（零基础讲解）：
%
% 【前置知识一：灰度直方图】
%   灰度图像中，每个像素的灰度值在 0~255 之间。
%   灰度直方图就是：统计灰度值=0 的像素有多少个、=1 的有多少个……=255 的有多少个，
%   然后画成柱状图。横轴是灰度值（0~255），纵轴是该灰度值的像素个数。
%
% 【前置知识二：什么是"类"（Class）？】
%   OTSU 把图像中的像素分成两类：
%     背景类（Background）：灰度值 <= 当前阈值 t 的像素
%     前景类（Foreground）：灰度值 >  当前阈值 t 的像素
%   这个阈值 t 是我们自己定的，OTSU 的任务就是自动找到最合适的 t。
%
% 【前置知识三：什么是"权重"（w）？】
%   权重就是一个类在整张图中所占的比例。
%   w1 = 背景类像素数量 / 图像总像素数量
%   w2 = 前景类像素数量 / 图像总像素数量
%   显然 w1 + w2 = 1（100%）
%
% 【前置知识四：什么是"平均灰度"（μ，念 mu）？】
%   平均灰度 = 一个类中所有像素的灰度值之和 / 像素个数
%   也就是这个类的"平均亮度"。
%   u1 = 背景类的平均灰度
%   u2 = 前景类的平均灰度
%
% 【OTSU 的核心公式：类间方差 σ_B²】
%   OTSU 用"类间方差"来衡量一个阈值 t 分得好不好：
%     σ_B² = w1 × w2 × (u1 - u2)²
%
%   公式解读：
%     w1 × w2 是两组权重之积 —— 两组规模越均衡（不是悬殊的 99% vs 1%），这个值越大
%     (u1 - u2)² 是两组平均灰度差的平方 —— 两组亮度差距越大，这个值越大
%     两者相乘：既要求两组亮度差距大，又要求两组规模不要悬殊
%
%   为什么 OTSU 能找到最优阈值？
%   遍历所有可能的 t（从 0 到 255），计算每个 t 对应的 σ_B²，
%   σ_B² 最大的那个 t，就是最优阈值。
%   原因：σ_B² 最大意味着"前景和背景分得最清楚"。
%
%======================================================================


function OTSU_result = MyOTSU(img)

    % -----------------------------------------------------------------------
    % 【第 0 步】类型转换 —— uint8 → double
    % -----------------------------------------------------------------------
    % 和迭代法一样，需要把 uint8 转成 double，避免后续除法等数学运算出错
    % double() 转换后数值不变（200 还是 200.0），只是类型变了
    img_d = double(img);


    % -----------------------------------------------------------------------
    % 【第 1 步】手动计算灰度直方图
    % -----------------------------------------------------------------------
    %
    % 为什么不用现成的 imhist() 函数？
    %   这里手动写一遍，能帮助你理解直方图到底是怎么算出来的。
    %
    % grayLevels = 256
    %   灰度值范围是 0~255，一共 256 个等级
    %   我们用 histCounts(1) 统计灰度值=0 的像素个数，
    %   histCounts(2) 统计灰度值=1 的像素个数……以此类推
    %
    % zeros(256, 1)
    %   创建长度为 256 的列向量，全部初始化为 0
    %   用于存放每个灰度等级的像素计数
    grayLevels = 256;
    histCounts = zeros(grayLevels, 1);


    % -----------------------------------------------------------------------
    % 遍历图像中每一个像素，统计各灰度等级的出现次数
    % -----------------------------------------------------------------------
    %
    % numel(img_d)
    %   numel = number of elements，返回矩阵中总共有多少个元素（像素总数）
    %   对于 100×100 的图像，numel(img_d) = 10000
    %
    % for i = 1:numel(img_d)
    %   从 1 循环到总像素数，依次处理每个像素
    %
    % val = img_d(i) + 1
    %   img_d(i) 是第 i 个像素的灰度值（范围 0~255）
    %   +1 是因为 MATLAB 数组索引从 1 开始，不是从 0 开始
    %   所以：
    %     灰度值 0 → val=1  → 放到 histCounts(1)
    %     灰度值 255→ val=256 → 放到 histCounts(256)
    %
    % 边界处理（防止极端情况出错）：
    %   if val < 1, val = 1; end   —— 如果出现负数（理论上不应该有），强行归为第1个等级
    %   if val > grayLevels, val = grayLevels; end —— 如果超出255，归为最后一个等级
    %
    % histCounts(val) = histCounts(val) + 1
    %   把对应灰度等级的计数器 +1
    %
    % 循环结束后，histCounts(k) = 灰度值 (k-1) 在图像中出现的次数
    for i = 1:numel(img_d)
        val = img_d(i) + 1;                     % MATLAB 索引从1开始，灰度0→索引1
        if val < 1, val = 1; end                % 防止负数索引（理论上不会有）
        if val > grayLevels, val = grayLevels; end % 防止超过256
        histCounts(val) = histCounts(val) + 1;  % 对应灰度等级计数+1
    end


    % -----------------------------------------------------------------------
    % 【第 2 步】计算直方图的概率分布（归一化）
    % -----------------------------------------------------------------------
    %
    % totalPixels = sum(histCounts)
    %   把所有灰度等级的计数加起来，得到图像的总像素数
    %   验证：totalPixels 应该等于 rows × cols
    totalPixels = sum(histCounts);

    %
    % prob = histCounts / totalPixels
    %   把像素计数转换为概率（比例）
    %   prob(k) = 灰度值 (k-1) 在图像中出现的概率（0~1 之间的小数）
    %   直观理解：prob(k) ≈ histCounts(k) / 总像素数
    %
    % 为什么需要这一步？
    %   OTSU 公式 σ_B² = w1 × w2 × (u1 - u2)² 中的 w1 和 w2 是"比例"（概率），
    %   不是"像素个数"。把计数归一化为概率后，才能代入公式。
    %
    % 数学上，所有灰度等级的概率加起来 = 1（概率之和为1）
    prob = histCounts / totalPixels;


    % -----------------------------------------------------------------------
    % 【第 3 步】遍历所有可能的阈值，找出使类间方差最大的那个
    % -----------------------------------------------------------------------
    %
    % maxVariance = 0
    %   用来记录目前找到的最大"类间方差"值，初始为 0
    %   随着遍历，maxVariance 会被更新为更大的值
    %
    % optimalThreshold = 0
    %   用来记录使类间方差最大的那个阈值，初始为 0
    %   循环过程中不断更新，直到遍历完所有可能阈值
    maxVariance = 0;
    optimalThreshold = 0;


    % -----------------------------------------------------------------------
    % for t = 1:grayLevels
    %   遍历 t = 1, 2, 3, ..., 256
    %   注意：这里的 t 对应 MATLAB 数组索引，实际灰度值 = t-1（范围 0~255）
    % -----------------------------------------------------------------------
    for t = 1:grayLevels

        % ----- 3.1 计算背景类（灰度 <= t 的像素）的权重 w1 -----
        %
        % prob(1:t) 是概率数组中前 t 个元素（对应灰度值 0~t-1）
        % sum(prob(1:t)) 就是把这些概率全部加起来，即 w1
        %
        % w1 的含义：在所有像素中，灰度值在 [0, t-1] 范围内的像素占多少比例？
        %
        % if w1 == 0 || w1 == 1
        %     continue;
        % end
        %   跳过无效情况：
        %     w1 == 0：阈值太高，所有像素都是前景（背景为空，没意义）
        %     w1 == 1：阈值太低（t=1），所有像素都是背景（前景为空，没意义）
        %   continue 的作用：跳过本次循环剩余代码，直接进入下一次迭代
        w1 = sum(prob(1:t));
        if w1 == 0 || w1 == 1
            continue;
        end


        % ----- 3.2 计算前景类（灰度 > t 的像素）的权重 w2 -----
        %
        % 前景 = 所有像素 - 背景，所以 w2 = 1 - w1
        % 验证：w1 + w2 = 1
        w2 = 1 - w1;


        % ----- 3.3 计算背景类的平均灰度 u1（加权平均） -----
        %
        % u1 = sum(0×prob(1) + 1×prob(2) + ... + (t-1)×prob(t)) / w1
        %
        % 为什么用加权平均？
        %   普通平均 = (灰度值之和) / 个数
        %   加权平均 = (各灰度值 × 其概率)之和 / 权重
        %
        % MATLAB 实现：(0:t-1)' .* prob(1:t)
        %   (0:t-1)'    —— 列向量 [0; 1; 2; ...; t-1]，即各灰度值
        %   prob(1:t)   —— 行向量 [prob(1), prob(2), ..., prob(t)]
        %   .*          —— 逐元素乘法（对应位置相乘）
        %   结果是一个向量：[0×prob(1), 1×prob(2), ..., (t-1)×prob(t)]
        %   sum(...)    —— 把所有"灰度值 × 概率"的乘积累加起来
        %   / w1        —— 除以背景类的总权重（归一化）
        %
        % 最终得到：背景类像素的加权平均灰度值
        u1 = sum((0:t-1)' .* prob(1:t)) / w1;


        % ----- 3.4 计算前景类的平均灰度 u2（加权平均） -----
        %
        % 前景类的灰度范围是 [t, 255]，对应索引 [t+1, 256]
        %
        % prob(t+1:grayLevels) —— 取索引从 t+1 到 grayLevels(256) 的概率值
        % (t:grayLevels-1)'   —— 对应的灰度值：t, t+1, ..., 255
        %
        % 同样做加权平均，除以 w2 得到前景类的平均灰度
        %
        % 特殊情况：t = grayLevels = 256 时
        %   此时 t+1:grayLevels 是空集（没有前景像素），
        %   直接把 u2 设为 0（不影响最终结果，因为 w1==1 的情况在前面已跳过）
        if t < grayLevels
            u2 = sum((t:grayLevels-1)' .* prob(t+1:grayLevels)) / w2;
        else
            u2 = 0;
        end


        % ----- 3.5 计算当前阈值 t 的类间方差 σ_B² -----
        %
        % OTSU 核心公式：
        %   σ_B² = w1 × w2 × (u1 - u2)²
        %
        % 各部分含义：
        %   w1          —— 背景类权重（比例）
        %   w2          —— 前景类权重（比例）
        %   (u1 - u2)² —— 两类平均灰度之差的平方
        %
        % 直观理解：
        %   - 两类亮度差距越大（|u1-u2| 大），方差越大
        %   - 两类规模越均衡（w1 和 w2 都接近 0.5），方差越大
        %   - 两者共同决定 σ_B² 的大小
        %
        %   找一个 t，使得 σ_B² 最大，就是让"分得最清楚"
        sigma_B2 = w1 * w2 * (u1 - u2)^2;


        % ----- 3.6 更新最优阈值 -----
        %
        % 如果当前阈值 t 计算出的 σ_B² 比之前找到的最大值还大，
        % 就把 maxVariance 和 optimalThreshold 都更新为当前值。
        %
        % 最终遍历完所有 t 后，optimalThreshold 就是使类间方差最大的阈值
        %
        % optimalThreshold = t - 1
        %   注意：数组索引 t 对应实际灰度值 t-1
        %   所以 optimalThreshold 的范围是 0~255
        if sigma_B2 > maxVariance
            maxVariance = sigma_B2;
            optimalThreshold = t - 1;   % 转换回 0~255 灰度值范围
        end

    end   % 遍历所有阈值结束


    % -----------------------------------------------------------------------
    % 【第 4 步】用找到的最优阈值做二值化分割
    % -----------------------------------------------------------------------
    %
    % 二值化逻辑（和迭代法完全一样）：
    %   像素灰度 >= optimalThreshold  →  255（白色，前景）
    %   像素灰度 <  optimalThreshold  →  0  （黑色，背景）
    %
    % OTSU_result = img;
    %   —— 复制原图结构
    %   —— 批量赋值：img >= optimalThreshold 生成 true/false 数组，
    %     位置为 true 的像素赋值为 255（白色）
    %
    % uint8() 最后转回 uint8 格式（imshow 要求的格式）
    OTSU_result = img;
    OTSU_result(img >= optimalThreshold) = 255;
    OTSU_result(img < optimalThreshold) = 0;
    OTSU_result = uint8(OTSU_result);


    % -----------------------------------------------------------------------
    % 【第 5 步】在命令行窗口打印找到的最优阈值
    % -----------------------------------------------------------------------
    %
    % fprintf() 是格式化打印函数，类似 C 语言的 printf
    % '%d' 是占位符，代表一个整数（optimalThreshold 的值）
    % '\n' 是换行符
    %
    % 运行程序后，在 MATLAB 命令行窗口（Command Window）中会看到类似：
    %   "OTSU Optimal Threshold: 128"
    % 这样的输出
    fprintf('OTSU Optimal Threshold: %d\n', optimalThreshold);

end   % 函数结束
