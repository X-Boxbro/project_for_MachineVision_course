% ================================================================
% 中值滤波（Median Filtering）函数实现
% ================================================================
% function：定义一个函数
% 输入参数：img（待滤波的灰度图像）
% 输出参数：Medfilt2_result（中值滤波后的结果）
% ================================================================
function Medfilt2_result = MyMedfilt2(img)

    % 获取图像的尺寸
    % size(img) 返回 [height, width]（高度和宽度）
    % MATLAB 的图像坐标系：img(row, col)，行=垂直方向，列=水平方向
    % 注意：这和 C++ 的 img.at<uchar>(i, j) 是对应的（i=row, j=col）
    [height, width] = size(img);

    % 创建结果图像，先复制一份原图
    % 后续会逐像素覆盖这个副本
    % MATLAB 中直接赋值 = 就是复制（不会共享内存）
    Medfilt2_result = img;


    % ================================================================
    % 3x3 邻域中值滤波，使用 replicate 边界填充
    %
    % 什么是"3x3 邻域"？
    %   以像素 (i, j) 为中心，取它周围的 8 个邻居 + 自身，共 9 个像素。
    %   形状像一个 3 行 3 列的小方块：
    %     (i-1,j-1)  (i-1,j)  (i-1,j+1)
    %     (i,  j-1)  (i,  j)  (i,  j+1)
    %     (i+1,j-1)  (i+1,j)  (i+1,j+1)
    %
    % 什么是"replicate 边界填充"？
    %   当邻域超出图像边界时（如边缘像素），用边界像素的值填充越界的部分。
    %   比如：图像第一行第1列像素 (1,1) 的邻域，
    %   越出上边和左边的那几个位置，都用 (1,1) 自己的值填充。
    % ================================================================


    % 外层两个循环：遍历图像中的每个像素 (i, j)
    % i 从 1 到 height（垂直方向，行索引）
    % j 从 1 到 width（水平方向，列索引）
    for i = 1:height
        for j = 1:width


            % ================================================================
            % 第一步：提取 3x3 邻域的 9 个像素值
            % ================================================================
            % neighbor：空向量，用于存放 9 个邻域像素的灰度值
            % 在 MATLAB 中，向量/数组使用方括号 [] 创建
            neighbor = [];

            % 内层两个循环：遍历 3x3 邻域的每个位置
            % ki = -1, 0, 1（垂直偏移：上、同行、下）
            % kj = -1, 0, 1（水平偏移：左、同列、右）
            for ki = -1:1
                for kj = -1:1

                    % 计算当前邻域位置在原图中的坐标
                    % row = 中心行 i + 垂直偏移 ki
                    % col = 中心列 j + 水平偏移 kj
                    row = i + ki;
                    col = j + kj;

                    % ================================================================
                    % 边界处理（replicate 方式）
                    % ================================================================
                    % 当 row 或 col 超出 [1, height] 或 [1, width] 范围时，
                    % 把它们"夹取"到边界值。
                    %
                    % MATLAB 中图像坐标从 1 开始（不是从 0 开始！）
                    %   - 行索引 i 的范围：1 到 height
                    %   - 列索引 j 的范围：1 到 width
                    %
                    % max(1, min(row, height)) 的逻辑：
                    %   如果 row < 1，取 row = 1（上边界）
                    %   如果 row > height，取 row = height（下边界）
                    %   否则保持 row 不变
                    % min 同理处理水平方向的越界
                    %
                    % 举例：
                    %   当 i = 1（第一行）时，ki = -1 会使 row = 0
                    %   max(1, min(0, height)) = max(1, 0) = 1
                    %   越界的上方位置被"复制"成了第一行像素的值
                    row = max(1, min(row, height));
                    col = max(1, min(col, width));

                    % 从原图中取出邻域像素的灰度值，追加到 neighbor 向量末尾
                    % MATLAB 中矩阵索引语法：img(row, col)
                    % neighbor = [neighbor, img(row, col)] 的含义：
                    %   把 img(row, col) 的值添加到 neighbor 向量的末尾
                    %   每循环一次，neighbor 就增加一个元素
                    %   9 次循环后，neighbor 就是一个长度为 9 的向量
                    neighbor = [neighbor, img(row, col)];

                end  % 结束 kj 循环（水平偏移）
            end      % 结束 ki 循环（垂直偏移）


            % ================================================================
            % 第二步：对 9 个邻域像素值排序，取中位数
            % ================================================================
            % sort(neighbor)：对 neighbor 向量从小到大排序
            % MATLAB 的 sort 函数默认是升序（ascending）
            % 排序后，sorted(1) 是最小值，sorted(9) 是最大值
            sorted = sort(neighbor);

            % 取中位数：9 个元素的中位数就是第 5 个（sorted(5)）
            % 为什么是第 5 个？
            %   9 个数从小到大排：sorted(1), sorted(2), ..., sorted(9)
            %   中位数位置 = (9 + 1) / 2 = 5
            %   所以 sorted(5) 就是中位数
            %
            % 中位数的意义：
            %   如果 9 个数是 [1, 2, 5, 8, 9, 10, 12, 15, 20]
            %   中位数 = 9（不是平均值 (1+2+5+8+9+10+12+15+20)/9 ≈ 9.1）
            %   中位数对"异常值"（噪声点）不敏感：
            %     - 如果有一个噪声点 200，和其他正常像素混在一起
            %     - 排序后 200 会在末尾，中位数仍然是中间那个正常值
            %     - 但如果是平均值，200 会把均值拉得偏高
            %
            % 把中位数写入结果图像的第 (i, j) 个像素
            Medfilt2_result(i, j) = sorted(5);  % 9个元素的第5个就是中位数


        end  % 结束 j 循环（列）
    end      % 结束 i 循环（行）


    % ================================================================
    % 返回滤波后的图像
    % ================================================================
    % 循环结束后，Medfilt2_result 就是一个完整的滤波结果图
    % MATLAB 函数会自动把输出参数的值返回给调用者
    % 在 main.m 中，调用 Medfilt2_result = MyMedfilt2(img) 时，
    % 这里 return 的值就会赋给 main.m 中的 Medfilt2_result 变量

end  % 结束 function MyMedfilt2
