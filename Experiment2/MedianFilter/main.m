% ================================================================
% 中值滤波（Median Filtering）是什么？
% ================================================================
% 中值滤波是一种经典的"非线性"图像滤波方法。
%
% 首先回顾一下"均值滤波"（线性滤波）：
%   取中心像素周围 3x3 共 9 个像素的"平均值"替代中心像素。
%   优点：能去除噪声（把突兀的噪声点"平均"掉）
%   缺点：会让图像变模糊（细节也被平均掉了）
%
% "中值滤波"的思想不同：
%   取中心像素周围 3x3 共 9 个像素的"中位数"替代中心像素。
%   中位数 = 把 9 个数从小到大排列后，最中间那个数（第 5 个）。
%
% 中值滤波的效果：
%   - 去除"椒盐噪声"效果非常好（孤立的黑点、白点会被邻居替代）
%   - 对边缘的保持比均值滤波好（不会把边缘的灰度"平均"掉）
%   - 但仍然是"模糊"操作，细节会有一定损失
%
% 为什么叫"非线性"？
%   均值滤波可以用"卷积"描述（乘加运算），是线性的。
%   中值滤波需要排序取中位数，不能表示为简单的乘加运算，所以是非线性的。
% ================================================================


% ================================================================
% 主脚本文件：程序入口
% ================================================================
% 注意：.m 文件如果以 function 开头就是函数文件，
% 如果直接写代码就是"脚本文件"（Script）。
% 脚本文件可以直接运行（不需要被调用），从第一行执行到最后一行。
% main.m 就是主脚本，程序从这里开始执行。

% ================================================================
% 第 1 步：清理环境（每次运行程序前的标准准备）
% ================================================================
% clc：Clear Command Window，清空命令行窗口的显示内容
%       （视觉效果：命令行变干净了，但不影响变量）
clc;

% clear all：Clear Workspace，删除工作区中的所有变量
%            防止上一次运行留下的旧变量干扰本次运行
%            （比如上次运行创建了一个大数组，这次忘记重新赋值）
clear all;

% close all：Close all Figures，关闭所有打开的图像窗口
%            防止上一次运行的图像窗口还在屏幕上干扰视线
close all;


% ================================================================
% 第 2 步：读取图像
% ================================================================
% imread('testimg.jpg')：读取名为 testimg.jpg 的图像文件
% MATLAB 会把图像加载为一个矩阵（Matrix）：
%   - 彩色图像：height x width x 3 的三维矩阵（R、G、B 三个通道）
%   - 灰度图像：height x width 的二维矩阵
% 读取后，变量 img 就"代表"了这张图像。
img = imread('testimg.jpg');


% ================================================================
% 第 3 步：彩色图转灰度图
% ================================================================
% rgb2gray(img)：将 RGB 彩色图像转换为灰度图像
%
% 为什么需要灰度图？
%   - 彩色图有 R、G、B 三个通道，处理起来更复杂
%   - 对于滤波、边缘检测等操作，我们只需要亮度信息就够了
%   - 灰度图只有一个通道，处理更简单高效
%
% 转换原理（简化）：
%   灰度 = 0.299 * R + 0.587 * G + 0.114 * B
%   （绿色权重最大，因为人眼对绿色最敏感）
%
% 注意：rgb2gray 会直接修改 img 变量的内容（覆盖）
img = rgb2gray(img);


% ================================================================
% 第 4 步：调用中值滤波函数
% ================================================================
% MyMedfilt2 是我们自己实现的 3x3 中值滤波函数（定义在 MyMedfilt2.m 中）
% 输入：img（灰度图）
% 输出：Medfilt2_result（中值滤波后的结果图）
%
% 这里调用和普通函数调用一样：函数名(输入参数)
Medfilt2_result = MyMedfilt2(img);


% ================================================================
% 第 5 步：显示原图和滤波结果
% ================================================================
% figure：创建并打开一个新的图像窗口
%         如果不加这行，imshow 可能会复用上一个窗口，导致显示混乱
figure;

% subplot(m, n, p)：把一个窗口分成 m 行 n 列的网格，显示第 p 张图
% subplot(1, 2, 1)：1 行 2 列的网格，左边第 1 张图
subplot(1, 2, 1);

% imshow(img)：在当前位置显示图像 img
% title('文字')：给图像加一个标题
imshow(img);
title('Original Gray Image');  % 原始灰度图

% subplot(1, 2, 2)：1 行 2 列的网格，右边第 2 张图
subplot(1, 2, 2);

imshow(Medfilt2_result);
title('Median Filtered Image');  % 中值滤波后的图像

% 运行结果：
%   窗口左边显示原始灰度图（可能有噪声点，细节清晰）
%   窗口右边显示中值滤波后的图（噪声被去掉了，但略微模糊）
